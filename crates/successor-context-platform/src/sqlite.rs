	#[tokio::test]
	async fn cross_session_causation_rejected() {
		let (store, session_a) = store_with_session().await;
		let create_b = CreateSessionRequestV0 {
			workspace:  successor_protocol::platform_api::WorkspaceV0 {
				id:        "ws_test".to_string(),
				label:     "test".to_string(),
				root_hint: "/tmp".to_string(),
			},
			title:      "session b".to_string(),
			created_by: successor_protocol::platform_api::CreatedByV0 {
				client_kind: "cli".to_string(),
				client_id:   "tester".to_string(),
			},
		};
		let session_b = store
			.create_session(create_b)
			.await
			.expect("second session creation succeeds")
			.session_id;

		let in_b = append_request(
			session_b.as_str(),
			"evt_in_session_b",
			"idem-in-session-b",
			None,
			serde_json::json!({ "k": "v" }),
		);
		store
			.append_event(in_b)
			.await
			.expect("append into session b succeeds");

		// `evt_in_session_b` is a real, persisted event, but it belongs to a
		// different session; causation must not resolve across sessions.
		let request = append_request(
			session_a.as_str(),
			"evt_bad_causation",
			"idem-bad-causation",
			Some("evt_in_session_b"),
			serde_json::json!({ "k": "v" }),
		);
		let err = store
			.append_event(request)
			.await
			.expect_err("cross-session causation is rejected");
		assert!(err.to_string().starts_with("causation_violation:"), "unexpected error: {err}");

		let page = store
			.read_session_events(&session_a, 0, 10)
			.await
			.expect("read succeeds");
		assert_eq!(page.events.len(), 0, "rejected append must not leave a partial row");
	}

