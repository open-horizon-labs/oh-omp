	#[tokio::test]
	async fn rollback_leaves_no_partial_rows_after_validation_failure_mid_transaction() {
		let (store, session_id) = store_with_session().await;
		let good = append_request(
			session_id.as_str(),
			"evt_good",
			"idem-good",
			None,
			serde_json::json!({ "k": "v" }),
		);
		store
			.append_event(good)
			.await
			.expect("first append succeeds");

		let bad = append_request(
			session_id.as_str(),
			"evt_bad",
			"idem-bad",
			Some("evt_does_not_exist"),
			serde_json::json!({ "k": "v" }),
		);
		store
			.append_event(bad)
			.await
			.expect_err("invalid causation is rejected");

		// The failed append must not have allocated a sequence, inserted a raw
		// event row, or inserted an idempotency-key row: a subsequent valid
		// append gets seq 2 (not 3), and only two events are ever readable.
		let next = append_request(
			session_id.as_str(),
			"evt_next",
			"idem-next",
			None,
			serde_json::json!({ "k": "v" }),
		);
		let response = store
			.append_event(next)
			.await
			.expect("append after rollback succeeds");
		assert_eq!(
			response.session_seq, 2,
			"rolled-back attempt must not have consumed a sequence number"
		);

		let page = store
			.read_session_events(&session_id, 0, 10)
			.await
			.expect("read succeeds");
		assert_eq!(page.events.len(), 2);
	}

