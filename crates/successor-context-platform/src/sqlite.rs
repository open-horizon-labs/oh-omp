/// sqlx SQLite-backed implementation of [`RawEventAppendStore`].
///
/// The pool is deliberately capped at a single connection. Slice 0 has no
/// throughput requirement that needs concurrent `SQLite` writers, and a
/// single-connection pool serializes every `append_event`/`create_session`
/// call through one connection -- giving the "single writer transaction"
/// ruling for idempotency-check + seq-allocation + validation + persistence
/// a trivially correct implementation with no `BEGIN IMMEDIATE`/busy-retry
/// logic required. Concurrent callers still exercise real interleaving at
/// the call-site level; they queue for the connection rather than racing
/// inside `SQLite`, which is what actually guarantees dense, gapless
/// `session_seq` allocation under concurrent load.
pub struct SqliteAppendStore {
	pool: SqlitePool,
}

impl SqliteAppendStore {
	/// Opens (creating if missing) a `SQLite` database file at `path` and runs
	/// pending migrations.
	pub async fn connect(path: &str) -> Result<Self, sqlx::Error> {
		let options = SqliteConnectOptions::new()
			.filename(path)
			.create_if_missing(true)
			.journal_mode(SqliteJournalMode::Wal);
		Self::connect_with(options).await
	}

	/// Opens a private in-memory database and runs pending migrations.
	/// Intended for tests.
	pub async fn connect_in_memory() -> Result<Self, sqlx::Error> {
		let options: SqliteConnectOptions = "sqlite::memory:".parse()?;
		Self::connect_with(options).await
	}

	async fn connect_with(options: SqliteConnectOptions) -> Result<Self, sqlx::Error> {
		let pool = SqlitePoolOptions::new()
			.max_connections(1)
			.connect_with(options)
			.await?;
		sqlx::migrate!("./migrations").run(&pool).await?;
		Ok(Self { pool })
	}
}

/// Maps a storage-layer failure into a `PlatformError` without leaking
/// driver detail (file paths, SQL text, `SQLite` error strings) to callers.
/// The original error is still logged for operator diagnosis.
fn sqlx_error(err: sqlx::Error) -> PlatformError {
	tracing::error!(error = %err, "storage operation failed");
	PlatformError::new(ProtocolViolationCode::Internal, "storage operation failed")
}

/// Maps a JSON encode/decode failure on a stored row into a `PlatformError`
/// without leaking the offending payload. The original error is still
/// logged for operator diagnosis.
fn json_error(err: serde_json::Error) -> PlatformError {
	tracing::error!(error = %err, "storage payload serialization failed");
	PlatformError::new(ProtocolViolationCode::Internal, "storage payload serialization failed")
}

/// SQL expression producing the current UTC wall-clock time as an ISO 8601 /
/// RFC 3339 string with millisecond precision. Generated by `SQLite` itself so
/// the platform crate does not need a `chrono`/`time` dependency beyond the
/// `sqlx` bootstrap dependency this lane is authorized to add.
const NOW_EXPR: &str = "strftime('%Y-%m-%dT%H:%M:%fZ','now')";

/// Builds the full, platform-assigned `RawEventV0` for a request that has
/// passed the idempotency check and been assigned `session_seq`. Every field
/// is copied from the client-supplied request except `session_seq` itself,
/// which the request DTO structurally cannot carry.
fn request_to_candidate(request: &RawEventAppendRequestV0, session_seq: u64) -> RawEventV0 {
	RawEventV0 {
		schema_version: request.schema_version.clone(),
		event_id: request.event_id.clone(),
		session_seq,
		idempotency_key: request.idempotency_key.clone(),
		event_type: request.event_type.clone(),
		session_id: request.session_id.clone(),
		turn_id: request.turn_id.clone(),
		request_id: request.request_id.clone(),
		occurred_at: request.occurred_at.clone(),
		producer: request.producer.clone(),
		causation_event_id: request.causation_event_id.clone(),
		correlation_id: request.correlation_id.clone(),
		entity_ids: request.entity_ids.clone(),
		visibility: request.visibility.clone(),
		redaction: request.redaction.clone(),
		payload: request.payload.clone(),
		artifact: request.artifact.clone(),
	}
}

impl RawEventAppendStore for SqliteAppendStore {
	fn create_session(
		&self,
		request: CreateSessionRequestV0,
	) -> BoxFuture<'_, PlatformResult<CreateSessionResponseV0>> {
		Box::pin(async move {
			let session_id = session::new_session_id();
			let workspace_json = serde_json::to_string(&request.workspace).map_err(json_error)?;
			let created_by_json = serde_json::to_string(&request.created_by).map_err(json_error)?;

			let mut conn = self.pool.acquire().await.map_err(sqlx_error)?;
			let sql = format!(
				"INSERT INTO sessions (session_id, workspace_json, title, created_by_json, \
				 created_at, last_session_seq) VALUES (?, ?, ?, ?, {NOW_EXPR}, 0) RETURNING created_at"
			);
			let created_at: String = sqlx::query_scalar(&sql)
				.bind(session_id.as_str())
				.bind(&workspace_json)
				.bind(&request.title)
				.bind(&created_by_json)
				.fetch_one(&mut *conn)
				.await
				.map_err(sqlx_error)?;

			Ok(CreateSessionResponseV0 { session_id, created_at })
		})
	}

	fn append_event(
		&self,
		request: RawEventAppendRequestV0,
	) -> BoxFuture<'_, PlatformResult<RawEventAppendResponseV0>> {
		Box::pin(async move {
			let candidate_fingerprint =
				idempotency::fingerprint(&request).map_err(violation_to_platform_error)?;

			let mut tx = self.pool.begin().await.map_err(sqlx_error)?;

			let session_exists = sqlx::query("SELECT 1 FROM sessions WHERE session_id = ?")
				.bind(request.session_id.as_str())
				.fetch_optional(&mut *tx)
				.await
				.map_err(sqlx_error)?;
			if session_exists.is_none() {
				return Err(PlatformError::new(
					ProtocolViolationCode::NotFound,
					format!("session {} not found", request.session_id),
				));
			}

			if let Some(row) = sqlx::query(
				"SELECT fingerprint, response_json FROM idempotency_keys WHERE session_id = ? AND \
				 idempotency_key = ?",
			)
			.bind(request.session_id.as_str())
			.bind(&request.idempotency_key)
			.fetch_optional(&mut *tx)
			.await
			.map_err(sqlx_error)?
			{
				let stored_fingerprint: String = row.try_get("fingerprint").map_err(sqlx_error)?;
				let response_json: String = row.try_get("response_json").map_err(sqlx_error)?;

				return match idempotency::classify(&stored_fingerprint, &candidate_fingerprint) {
					IdempotencyOutcome::Replay => {
						let mut response: RawEventAppendResponseV0 =
							serde_json::from_str(&response_json).map_err(json_error)?;
						response.duplicate = true;
						tx.commit().await.map_err(sqlx_error)?;
						Ok(response)
					},
					IdempotencyOutcome::Conflict => Err(PlatformError::new(
						ProtocolViolationCode::DuplicateIdempotencyKey,
						format!(
							"idempotency_key {} was already used in session {} with a different request",
							request.idempotency_key, request.session_id
						),
					)),
				};
			}

			let event_id_taken = sqlx::query("SELECT 1 FROM raw_events WHERE event_id = ?")
				.bind(request.event_id.as_str())
				.fetch_optional(&mut *tx)
				.await
				.map_err(sqlx_error)?;
			if event_id_taken.is_some() {
				return Err(PlatformError::new(
					ProtocolViolationCode::Conflict,
					format!("event_id {} is already in use", request.event_id),
				));
			}

			let next_seq: i64 = sqlx::query_scalar(
				"UPDATE sessions SET last_session_seq = last_session_seq + 1 WHERE session_id = ? \
				 RETURNING last_session_seq",
			)
			.bind(request.session_id.as_str())
			.fetch_one(&mut *tx)
			.await
			.map_err(sqlx_error)?;
			let session_seq = u64::try_from(next_seq).map_err(|_| {
				PlatformError::new(ProtocolViolationCode::Internal, "sequence allocation overflow")
			})?;

			let history_rows = sqlx::query(
				"SELECT event_json FROM raw_events WHERE session_id = ? ORDER BY session_seq ASC",
			)
			.bind(request.session_id.as_str())
			.fetch_all(&mut *tx)
			.await
			.map_err(sqlx_error)?;
			let mut events: Vec<RawEventV0> = Vec::with_capacity(history_rows.len() + 1);
			for row in &history_rows {
				let json: String = row.try_get("event_json").map_err(sqlx_error)?;
				events.push(serde_json::from_str(&json).map_err(json_error)?);
			}

			let candidate = request_to_candidate(&request, session_seq);
			candidate
				.validate_structure()
				.map_err(violation_to_platform_error)?;
			events.push(candidate.clone());
			validate_raw_event_stream(&events).map_err(violation_set_to_platform_error)?;

			let event_json = serde_json::to_string(&candidate).map_err(json_error)?;
			let stored_at: String = sqlx::query_scalar(&format!("SELECT {NOW_EXPR}"))
				.fetch_one(&mut *tx)
				.await
				.map_err(sqlx_error)?;

			sqlx::query(
				"INSERT INTO raw_events (event_id, session_id, session_seq, idempotency_key, \
				 event_json, stored_at) VALUES (?, ?, ?, ?, ?, ?)",
			)
			.bind(candidate.event_id.as_str())
			.bind(candidate.session_id.as_str())
			.bind(session_seq as i64)
			.bind(&candidate.idempotency_key)
			.bind(&event_json)
			.bind(&stored_at)
			.execute(&mut *tx)
			.await
			.map_err(sqlx_error)?;

			let response = RawEventAppendResponseV0 {
				event_id: candidate.event_id.clone(),
				session_seq,
				duplicate: false,
				stored_at,
				source_envelope_id: candidate.entity_ids.source_envelope_id.clone(),
				artifact_id: candidate.entity_ids.artifact_id.clone(),
			};
			let response_json = serde_json::to_string(&response).map_err(json_error)?;

			sqlx::query(
				"INSERT INTO idempotency_keys (session_id, idempotency_key, fingerprint, event_id, \
				 response_json) VALUES (?, ?, ?, ?, ?)",
			)
			.bind(candidate.session_id.as_str())
			.bind(&candidate.idempotency_key)
			.bind(&candidate_fingerprint)
			.bind(candidate.event_id.as_str())
			.bind(&response_json)
			.execute(&mut *tx)
			.await
			.map_err(sqlx_error)?;

			tx.commit().await.map_err(sqlx_error)?;

			Ok(response)
		})
	}

	fn read_event<'a>(
		&'a self,
		event_id: &'a EventId,
	) -> BoxFuture<'a, PlatformResult<Option<RawEventV0>>> {
		Box::pin(async move {
			let mut conn = self.pool.acquire().await.map_err(sqlx_error)?;
			let row = sqlx::query("SELECT event_json FROM raw_events WHERE event_id = ?")
				.bind(event_id.as_str())
				.fetch_optional(&mut *conn)
				.await
				.map_err(sqlx_error)?;
			match row {
				Some(row) => {
					let json: String = row.try_get("event_json").map_err(sqlx_error)?;
					let event: RawEventV0 = serde_json::from_str(&json).map_err(json_error)?;
					Ok(Some(event))
				},
				None => Ok(None),
			}
		})
	}

	fn read_session_events<'a>(
		&'a self,
		session_id: &'a SessionId,
		after_seq: u64,
		limit: u32,
	) -> BoxFuture<'a, PlatformResult<EventPageV0>> {
		Box::pin(async move {
			let mut conn = self.pool.acquire().await.map_err(sqlx_error)?;

			let session_exists = sqlx::query("SELECT 1 FROM sessions WHERE session_id = ?")
				.bind(session_id.as_str())
				.fetch_optional(&mut *conn)
				.await
				.map_err(sqlx_error)?;
			if session_exists.is_none() {
				return Err(PlatformError::new(
					ProtocolViolationCode::NotFound,
					format!("session {session_id} not found"),
				));
			}

			let fetch_limit = i64::from(limit) + 1;
			let after_seq_i64 = i64::try_from(after_seq).unwrap_or(i64::MAX);
			let rows = sqlx::query(
				"SELECT event_json, session_seq FROM raw_events WHERE session_id = ? AND session_seq \
				 > ? ORDER BY session_seq ASC LIMIT ?",
			)
			.bind(session_id.as_str())
			.bind(after_seq_i64)
			.bind(fetch_limit)
			.fetch_all(&mut *conn)
			.await
			.map_err(sqlx_error)?;

			let has_more = i64::try_from(rows.len()).unwrap_or(i64::MAX) > i64::from(limit);
			let limit_usize = limit as usize;
			let mut events = Vec::with_capacity(rows.len().min(limit_usize));
			let mut next_after_seq = after_seq;
			for row in rows.into_iter().take(limit_usize) {
				let json: String = row.try_get("event_json").map_err(sqlx_error)?;
				let seq: i64 = row.try_get("session_seq").map_err(sqlx_error)?;
				next_after_seq = u64::try_from(seq).unwrap_or(next_after_seq);
				events.push(serde_json::from_str(&json).map_err(json_error)?);
			}

			Ok(EventPageV0::new(session_id.clone(), events, next_after_seq, has_more))
		})
	}
}

